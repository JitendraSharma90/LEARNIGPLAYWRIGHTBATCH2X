//Exponential Operator
let a = 2;
console.log(a ** 3); // 8 (2 raised to the power of 3)
console.log(a ** 4); // 16 (2 raised to the power of 4)
//2 ^^ 3 = 2*2*2 = 8
//2 ^^ 4 = 2*2*2*2 = 16
//2^3 = 2*2*2 = 8
//2^4 = 2*2*2*2 = 16    

let x = 5;
console.log(x **= 2); // 25 (x is now 5 raised to the power of 2)
console.log(x); // 25 (x is now 25) 
let y = 3;
let z = 4;
console.log(y ** z); // 81 (3 raised to the power of 4)
