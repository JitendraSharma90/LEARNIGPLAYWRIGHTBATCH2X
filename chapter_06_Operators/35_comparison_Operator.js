//comparison Operators
let x = 10;
let y = 20;
console.log(x == y); // false (Equality)
console.log(x != y);
console.log(x > y); // false (Greater than)
console.log(x < y); // true (Less than)
console.log(x >= y);// example 10 >= 10 true (Greater than or equal to)//10 >= 20 false or 10 === 20 false// or Gate
console.log(x <= y); // true (Less than or equal to)//10 <= 20 true or 10 ===20 false


