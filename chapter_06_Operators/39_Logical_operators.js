// && -> AND gate
// || -> OR gate
// ! -> NOT gate    
let a = 10;
let b = 20;
console.log(a > 5 && b > 15); // true (both conditions are true)
console.log(a > 15 || b > 15); // true (one of the conditions is true)
console.log(!(a > 5)); // false (negation of true is false) 


console.log(5 != "Mohit"); // value  5 is not equal to "Mohit" // true (loose inequality, type coercion occurs)
console.log(5 !== "Mohit"); // value or data type 5 is not equal to "Mohit" // true (strict inequality, no type coercion)   



