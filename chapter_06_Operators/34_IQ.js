//compound assignment operator

let x = 10;
x += 5; // x = x + 5
console.log(x); // 15 

//Compound operators
let a = 10;
a += 5; // a = a + 5
console.log(a); // 15
a -= 3; // a = a - 3
console.log(a); // 12
a *= 2; // a = a * 2
console.log(a); // 24
a /= 4; // a = a / 4
console.log(a); // 6
a %= 4; // a = a % 4
console.log(a); // 2
a **= 3; // a = a ** 3
console.log(a); // 8 (2 raised to the power of 3)   

